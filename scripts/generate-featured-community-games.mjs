import { access, readFile, writeFile } from "node:fs/promises";
import {
  buildFeaturedCommunityAllowlist,
  buildFeaturedCommunityPackages,
} from "./featured-community-game-generator.mjs";

const packages = buildFeaturedCommunityPackages();
const allowlist = buildFeaturedCommunityAllowlist(packages);
const fixture = `${JSON.stringify(packages, null, 2)}\n`;
const argumentsSet = new Set(process.argv.slice(2));
const checkOnly = argumentsSet.has("--check");
const requireApp = argumentsSet.has("--require-app");

await writeGenerated(
  new URL("../community/featured-games-v1.js", import.meta.url),
  generatedModule("featuredCommunityPackages", packages),
);
await writeGenerated(
  new URL("../community/allowlist-v1.js", import.meta.url),
  generatedModule("communityAllowlist", allowlist),
);
await writeGenerated(
  new URL("../tests/fixtures/featured-community-packages-v1.json", import.meta.url),
  fixture,
);

const appFixture = new URL(
  "../../Jotto/JottoTests/Fixtures/featured-community-packages-v1.json",
  import.meta.url,
);
if (await exists(appFixture)) {
  await writeGenerated(appFixture, fixture);
} else if (requireApp) {
  throw new Error(`App fixture is unavailable at ${appFixture.pathname}`);
}

function generatedModule(name, value) {
  return `// Generated by scripts/generate-featured-community-games.mjs. Do not edit by hand.\n`
    + `export const ${name} = Object.freeze(${JSON.stringify(value, null, 2)});\n`;
}

async function writeGenerated(url, contents) {
  if (!checkOnly) {
    await writeFile(url, contents);
    return;
  }
  const current = await readFile(url, "utf8");
  if (current !== contents) throw new Error(`Generated artifact is stale: ${url.pathname}`);
}

async function exists(url) {
  try {
    await access(url);
    return true;
  } catch {
    return false;
  }
}
